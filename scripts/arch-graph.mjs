// Generates docs/engineering/dependency-graph.generated.md, the folder-level
// import graph of `src/` as a Mermaid flowchart (ADR 0006: what can be derived
// from code is generated, not drawn by hand). Run it with `pnpm arch:graph`
// after a change that adds, removes or redirects imports between folders.
//
// It cruises with the same rules file as `pnpm arch` (`.dependency-cruiser.cjs`)
// so the picture and the gate see one graph, type-only imports included, and
// collapses each module into its folder:
// - `src/modules/<context>`: one node per bounded context, once contexts move
//   there (ADR 0001);
// - `src/lib/<area>`, `src/components/<area>`, `src/app/<segment>`: today's
//   areas, until they move;
// - any other top-level entry of `src/` (hooks, i18n, middleware.ts, …).
// Test files and the `src/test/` support folder are left out.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { cruise } from "dependency-cruiser";
import extractDepcruiseOptions from "dependency-cruiser/config-utl/extract-depcruise-options";
import extractTSConfig from "dependency-cruiser/config-utl/extract-ts-config";

// Every path below, and every path in the cruise result, is relative to the
// repository root.
process.chdir(fileURLToPath(new URL("..", import.meta.url)));

const OUTPUT = "docs/engineering/dependency-graph.generated.md";
const COLLAPSE = "^src/(modules|lib|components|app)/[^/]+|^src/[^/]+";

const options = await extractDepcruiseOptions("./.dependency-cruiser.cjs");
const { output } = await cruise(
  ["src"],
  {
    ...options,
    // A picture, not a check: `pnpm arch` reports the violations.
    validate: false,
    includeOnly: "^src/",
    exclude: { path: [...options.exclude.path, "^src/test/"] },
    collapse: COLLAPSE,
    outputType: "mermaid",
  },
  {},
  { tsConfig: extractTSConfig(options.tsConfig.fileName) }
);

writeFileSync(
  OUTPUT,
  `# Dependency graph (generated)

> Generated by \`pnpm arch:graph\` (\`scripts/arch-graph.mjs\`) from \`.dependency-cruiser.cjs\`. Do not
> edit by hand: change the code and run the command again. An arrow means "imports", type-only imports
> included. The rules this graph is checked against are in [ADR 0007](../adr/0007-architecture-enforcement-in-stages.md)
> and [architecture.md](architecture.md#layers-and-dependency-rules).

\`\`\`mermaid
${output.trimEnd()}
\`\`\`
`
);
console.log(`Wrote ${OUTPUT}`);
